// Запуск и отмена привязки по QR — строго по очереди (сверка PR #30).
//
// Окно просит код сразу при открытии. Закрой его, пока запрос запуска ещё
// в пути, — и отмена могла бы прийти на сервер раньше запуска: сервер
// отменил бы «ничего», а потом начал бы вход, которого уже никто не видит.
// Такой вход живёт до таймаута steam-session (30 с с начала опроса), всё это
// время держит «привязка уже идёт», а подтверди его кто-нибудь по ссылке из
// состояния — аккаунт привязался бы без окна.
//
// Поэтому каждый запрос уходит только после ответа на предыдущий: отмена —
// после ответа на запуск, то есть после того, как сервер его уже выполнил.
// Сервер разбирает запрос синхронно (accounts.ts, linkStart/linkCancel),
// так что ответ на запуск означает: процесс входа уже заведён, и отмена его
// погасит. Проверка — rig/server/linkflow.test.ts, на настоящем сервере.

type Send = (url: string, body: unknown) => Promise<any>

export function linkFlow(send: Send) {
  let last: Promise<unknown> = Promise.resolve()
  const queue = <T>(run: () => Promise<T>): Promise<T> => {
    const p = last.then(run)
    last = p.catch(() => { })
    return p
  }
  return {
    start: (body: unknown) => queue(() => send('/api/accounts/link', body)),
    cancel: () => queue(() => send('/api/accounts/link/cancel', {})),
  }
}
